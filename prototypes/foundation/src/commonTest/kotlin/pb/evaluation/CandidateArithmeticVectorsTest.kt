package pb.evaluation
import kotlin.test.Test
import kotlin.test.assertEquals

/** 60 vectors generated with independent Python decimal, precision 12 / ROUND_HALF_UP.
 * These test the explicit evaluation model, not confirmed PB hardware behavior. */
class CandidateArithmeticVectorsTest {
    @Test fun independentDecimalVectors() {
        val vectors = listOf(
        arrayOf("+", "0.1", "0.2", "0.3"),
        arrayOf("-", "0.1", "0.2", "-0.1"),
        arrayOf("*", "0.1", "0.2", "0.02"),
        arrayOf("/", "0.1", "0.2", "0.5"),
        arrayOf("+", "1", "3", "4"),
        arrayOf("-", "1", "3", "-2"),
        arrayOf("*", "1", "3", "3"),
        arrayOf("/", "1", "3", "0.333333333333"),
        arrayOf("+", "-1", "7", "6"),
        arrayOf("-", "-1", "7", "-8"),
        arrayOf("*", "-1", "7", "-7"),
        arrayOf("/", "-1", "7", "-0.142857142857"),
        arrayOf("+", "9.99999999999", "0.00000000001", "10.0000000000"),
        arrayOf("-", "9.99999999999", "0.00000000001", "9.99999999998"),
        arrayOf("*", "9.99999999999", "0.00000000001", "9.99999999999E-11"),
        arrayOf("/", "9.99999999999", "0.00000000001", "999999999999"),
        arrayOf("+", "1E-99", "10", "10.0000000000"),
        arrayOf("-", "1E-99", "10", "-10.0000000000"),
        arrayOf("*", "1E-99", "10", "1.0E-98"),
        arrayOf("/", "1E-99", "10", "1E-100"),
        arrayOf("+", "1E99", "3", "1.00000000000E+99"),
        arrayOf("-", "1E99", "3", "1.00000000000E+99"),
        arrayOf("*", "1E99", "3", "3E+99"),
        arrayOf("/", "1E99", "3", "3.33333333333E+98"),
        arrayOf("+", "-12.3456789012", "2.5", "-9.8456789012"),
        arrayOf("-", "-12.3456789012", "2.5", "-14.8456789012"),
        arrayOf("*", "-12.3456789012", "2.5", "-30.8641972530"),
        arrayOf("/", "-12.3456789012", "2.5", "-4.93827156048"),
        arrayOf("+", "999999999999", "11", "1.00000000001E+12"),
        arrayOf("-", "999999999999", "11", "999999999988"),
        arrayOf("*", "999999999999", "11", "1.10000000000E+13"),
        arrayOf("/", "999999999999", "11", "90909090909"),
        arrayOf("+", "0", "1", "1"),
        arrayOf("-", "0", "1", "-1"),
        arrayOf("*", "0", "1", "0"),
        arrayOf("/", "0", "1", "0"),
        arrayOf("+", "1.234567890125", "1", "2.23456789013"),
        arrayOf("-", "1.234567890125", "1", "0.234567890125"),
        arrayOf("*", "1.234567890125", "1", "1.23456789013"),
        arrayOf("/", "1.234567890125", "1", "1.23456789013"),
        arrayOf("+", "1E12", "1", "1.00000000000E+12"),
        arrayOf("-", "1E12", "1", "999999999999"),
        arrayOf("*", "1E12", "1", "1E+12"),
        arrayOf("/", "1E12", "1", "1E+12"),
        arrayOf("+", "-1E-80", "3", "3.00000000000"),
        arrayOf("-", "-1E-80", "3", "-3.00000000000"),
        arrayOf("*", "-1E-80", "3", "-3E-80"),
        arrayOf("/", "-1E-80", "3", "-3.33333333333E-81"),
        arrayOf("+", "123456789012", "0.003", "123456789012"),
        arrayOf("-", "123456789012", "0.003", "123456789012"),
        arrayOf("*", "123456789012", "0.003", "370370367.036"),
        arrayOf("/", "123456789012", "0.003", "4.1152263004E+13"),
        arrayOf("+", "0.000123456789012", "7", "7.00012345679"),
        arrayOf("-", "0.000123456789012", "7", "-6.99987654321"),
        arrayOf("*", "0.000123456789012", "7", "0.000864197523084"),
        arrayOf("/", "0.000123456789012", "7", "0.0000176366841446"),
        arrayOf("+", "3.14159265359", "2", "5.14159265359"),
        arrayOf("-", "3.14159265359", "2", "1.14159265359"),
        arrayOf("*", "3.14159265359", "2", "6.28318530718"),
        arrayOf("/", "3.14159265359", "2", "1.57079632680")
        )
        for ((op, a, b, expected) in vectors) {
            assertEquals(0, CandidateArithmeticProbe.calculate(op, a, b).compareTo(DecimalProbe.parse(expected)), "$a $op $b expected $expected")
        }
    }
}
